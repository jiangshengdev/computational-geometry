import { expect, test } from '@playwright/test'

for (const browserName of ['chromium', 'firefox', 'webkit'] as const) {
  const browserTest = test.extend({ browserName })
  browserTest(`禅模式切换、辅助栏状态恢复与回放 ${browserName}`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()) })
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/cases/crossing/learn?step=3')
    await expect(page).toHaveTitle('普通交叉 · 逐步学习 · BO 结果查看器')
    const toggle = page.getByRole('switch', { name: '禅模式', exact: true })
    const controls = page.getByRole('region', { name: '回放控制' })
    const left = page.getByRole('complementary', { name: '左侧辅助栏' })
    const right = page.getByRole('complementary', { name: '右侧辅助栏' })
    await expect(toggle).not.toBeChecked()
    await page.getByRole('button', { name: '展开左侧辅助栏' }).click()
    await page.getByRole('button', { name: '放大', exact: true }).click()
    const geometry = page.locator('g[data-layer="geometry"]')
    await expect(geometry).toHaveAttribute('transform', /scale\(1.4\)/)
    const transform = (await geometry.getAttribute('transform'))!
    await page.getByText('禅模式', { exact: true }).click()
    await expect(toggle).toBeChecked()
    for (const region of [left, right, controls]) await expect(region).toBeHidden()
    await expect(page).toHaveURL(/step=3$/)
    await expect(geometry).toHaveAttribute('transform', transform)
    await page.keyboard.press('z')
    await expect(toggle).not.toBeChecked()
    await expect(left).toHaveAttribute('data-expanded', 'true')
    await expect(right).toHaveAttribute('data-expanded', 'false')
    await expect(controls).toBeVisible()
    await expect(geometry).toHaveAttribute('transform', transform)
    await page.keyboard.down('z')
    await page.keyboard.down('z')
    await page.keyboard.up('z')
    await expect(toggle).toBeChecked()
    await page.keyboard.press('ArrowRight')
    await expect(page).toHaveURL(/step=4$/)
    await page.keyboard.press('ArrowLeft')
    await expect(page).toHaveURL(/step=3$/)
    await page.keyboard.press('r')
    await expect(page).toHaveURL(/step=0$/)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(page.getByText('禅模式', { exact: true })).toBeInViewport()
    for (const region of [left, right, controls]) await expect(region).toBeHidden()
    for (const name of ['几何视图', '核心代码回放', '核心变量']) {
      await expect(page.getByRole('region', { name, exact: true })).toBeVisible()
    }
    await page.getByText('禅模式', { exact: true }).click()
    await expect(controls).toBeVisible()
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    expect(errors).toEqual([])
  })

  browserTest(`禅模式记忆与快捷键避让 ${browserName}`, async ({ page }) => {
    await page.goto('/cases/crossing/learn?step=3')
    const toggle = page.getByRole('switch', { name: '禅模式', exact: true })
    await page.getByRole('spinbutton', { name: '跳转步骤' }).press('z')
    await expect(toggle).not.toBeChecked()
    await page.getByRole('button', { name: '说明与帮助', exact: true }).click()
    await page.keyboard.press('z')
    await expect(toggle).not.toBeChecked()
    await page.getByRole('button', { name: '关闭帮助', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(page.getByRole('button', { name: '说明与帮助', exact: true })).toBeFocused()
    for (const key of ['Control+z', 'Meta+z', 'Alt+z', 'Shift+z']) {
      await page.keyboard.press(key)
      await expect(toggle).not.toBeChecked()
    }
    await page.getByRole('link', { name: '返回列表', exact: true }).focus()
    await page.keyboard.press('z')
    await expect(toggle).toBeChecked()
    await page.reload()
    await expect(toggle).toBeChecked()
    await expect(page.getByRole('region', { name: '回放控制' })).toBeHidden()
    await page.getByRole('link', { name: '返回结果查看器' }).click()
    await expect(toggle).toHaveCount(0)
    await page.keyboard.press('z')
    await page.getByRole('link', { name: /开始逐步学习/ }).click()
    await expect(toggle).toBeChecked()
    await page.goto('/cases/multiway-endpoints/learn')
    await expect(toggle).toBeChecked()
    await page.getByText('禅模式', { exact: true }).click()
    await page.reload()
    await expect(toggle).not.toBeChecked()
    await expect(page.getByRole('region', { name: '回放控制' })).toBeVisible()
  })
}
