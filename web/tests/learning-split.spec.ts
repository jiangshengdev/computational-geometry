import { expect, test, type Locator } from '@playwright/test'

async function box(locator: Locator) {
  await expect(locator).toBeVisible()
  return (await locator.boundingBox())!
}

for (const browserName of ['chromium', 'firefox', 'webkit'] as const) {
  const browserTest = test.extend({ browserName })
  browserTest(`中央比例拖动、恢复与窄屏 ${browserName}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/cases/crossing/learn?step=1')
    const splitter = page.getByRole('separator', { name: '画布与代码区和变量区宽度', exact: true })
    const geometry = page.getByRole('region', { name: '几何视图', exact: true })
    const code = page.getByRole('region', { name: '核心代码回放', exact: true })
    const variables = page.getByRole('region', { name: '核心变量', exact: true })
    const start = await box(splitter)
    const before = await box(geometry)
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
    await page.mouse.down()
    await page.mouse.move(start.x + 100, start.y + start.height / 2, { steps: 6 })
    await page.mouse.up()
    const after = await box(geometry)
    expect(after.width).toBeGreaterThan(before.width + 80)
    expect((await box(code)).width).toBe(after.width)
    await expect(page).toHaveURL(/step=1$/)
    await page.reload()
    expect(Math.abs((await box(geometry)).width - after.width)).toBeLessThanOrEqual(2)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(splitter).toBeHidden()
    const narrow = await box(geometry)
    const narrowCode = await box(code)
    expect(narrowCode.y).toBeGreaterThanOrEqual(narrow.y + narrow.height)
    expect((await box(variables)).y).toBeGreaterThanOrEqual(narrowCode.y + narrowCode.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize({ width: 1440, height: 900 })
    expect(Math.abs((await box(geometry)).width - after.width)).toBeLessThanOrEqual(2)
    await splitter.dblclick()
    expect(Math.abs((await box(geometry)).width - (await box(variables)).width)).toBeLessThanOrEqual(2)
    await page.reload()
    expect(Math.abs((await box(geometry)).width - (await box(variables)).width)).toBeLessThanOrEqual(2)
  })
  browserTest(`画布代码高度拖动、独立记忆与键盘恢复 ${browserName}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/cases/crossing/learn?step=1')
    const heightSplitter = page.getByRole('separator', { name: '画布与代码区高度', exact: true })
    const widthSplitter = page.getByRole('separator', { name: '画布与代码区和变量区宽度', exact: true })
    const geometry = page.getByRole('region', { name: '几何视图', exact: true })
    const code = page.getByRole('region', { name: '核心代码回放', exact: true })
    const variables = page.getByRole('region', { name: '核心变量', exact: true })
    const controls = page.getByRole('region', { name: '回放控制', exact: true })
    await expect(heightSplitter).toHaveAttribute('aria-orientation', 'horizontal')
    await widthSplitter.focus()
    await widthSplitter.press('ArrowRight')
    const originalCanvas = await box(geometry)
    const originalCode = await box(code)
    const unchanged = [await box(variables), await box(controls), await box(widthSplitter)]
    const ratio = async () => {
      const canvasBox = await box(geometry), codeBox = await box(code)
      return canvasBox.height / (canvasBox.height + codeBox.height)
    }
    expect(Math.abs(await ratio() - 4 / 7)).toBeLessThan(0.003)
    const handle = await box(heightSplitter)
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
    await page.mouse.down()
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2 - 90, { steps: 6 })
    await page.mouse.up()
    const resizedCanvas = await box(geometry)
    const resizedCode = await box(code)
    expect(resizedCanvas.height).toBeLessThan(originalCanvas.height - 80)
    expect(resizedCode.height).toBeGreaterThan(originalCode.height + 80)
    expect({ x: resizedCanvas.x, width: resizedCanvas.width }).toEqual({ x: originalCanvas.x, width: originalCanvas.width })
    expect({ x: resizedCode.x, width: resizedCode.width }).toEqual({ x: originalCode.x, width: originalCode.width })
    expect([await box(variables), await box(controls), await box(widthSplitter)]).toEqual(unchanged)
    await expect(page).toHaveURL(/step=1$/)
    const preferred = await ratio()
    await page.reload()
    await expect.poll(async () => Math.abs(await ratio() - preferred)).toBeLessThan(0.003)
    expect((await box(geometry)).width).toBe(originalCanvas.width)
    for (const viewport of [{ width: 390, height: 844 }, { width: 1440, height: 650 }]) {
      await page.setViewportSize(viewport)
      await expect(heightSplitter).toBeHidden()
      const canvasBox = await box(geometry), codeBox = await box(code)
      expect(codeBox.y).toBeGreaterThanOrEqual(canvasBox.y + canvasBox.height)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.setViewportSize({ width: 1440, height: 900 })
      await expect(heightSplitter).toBeVisible()
      await expect.poll(async () => Math.abs(await ratio() - preferred)).toBeLessThan(0.003)
    }
    await heightSplitter.focus()
    await heightSplitter.press('ArrowDown')
    const enlarged = await ratio()
    expect(enlarged).toBeGreaterThan(preferred)
    await heightSplitter.press('ArrowUp')
    expect(Math.abs(await ratio() - preferred)).toBeLessThan(0.003)
    await expect(page).toHaveURL(/step=1$/)
    await heightSplitter.press('Home')
    expect(Math.abs(await ratio() - 4 / 7)).toBeLessThan(0.003)
    await heightSplitter.press('ArrowUp')
    expect(await ratio()).toBeLessThan(4 / 7 - 0.01)
    await heightSplitter.dblclick()
    expect(Math.abs(await ratio() - 4 / 7)).toBeLessThan(0.003)
    expect((await box(geometry)).width).toBe(originalCanvas.width)
    await page.reload()
    expect(Math.abs(await ratio() - 4 / 7)).toBeLessThan(0.003)
    expect((await box(geometry)).width).toBe(originalCanvas.width)
    for (const edge of [0, 900]) {
      const currentHandle = await box(heightSplitter)
      await page.mouse.move(currentHandle.x + currentHandle.width / 2, currentHandle.y + currentHandle.height / 2)
      await page.mouse.down()
      await page.mouse.move(currentHandle.x + currentHandle.width / 2, edge, { steps: 6 })
      await page.mouse.up()
      expect((await box(geometry)).height).toBeGreaterThanOrEqual(180)
      expect((await box(code)).height).toBeGreaterThanOrEqual(180)
      expect([await box(variables), await box(controls), await box(widthSplitter)]).toEqual(unchanged)
      await expect(controls.getByRole('button', { name: '下一步', exact: true })).toBeInViewport()
      await expect(page).toHaveURL(/step=1$/)
    }
  })
}
