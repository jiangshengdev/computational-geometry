import { expect, test } from '@playwright/test'

for (const browserName of ['chromium', 'webkit'] as const) {
  const browserTest = test.extend({ browserName })
  browserTest(`主体布局预设选择、记忆与回放状态 ${browserName}`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()) })
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto('/bo/cases/crossing/learn?step=3')
    await expect(page).toHaveTitle('普通交叉 · 逐步学习 · BO 结果查看器')
    const layout = page.getByRole('button', { name: /主体布局比例/ })
    const variables = page.getByRole('region', { name: '核心变量', exact: true })
    await expect(variables).toBeVisible()
    const contents = await variables.innerText()
    await expect(layout).toContainText('2:3:3')
    await page.getByRole('button', { name: '展开左侧辅助栏' }).click()
    for (const ratio of ['1:2:2', '2:3:3', '1:1:1', '1:3:2', '1:2:3']) {
      await layout.click()
      await expect(page.getByRole('option')).toHaveCount(5)
      await page.getByRole('option', { name: ratio, exact: true }).click()
      await expect(page.getByRole('listbox')).toBeHidden()
      await expect(layout).toContainText(ratio)
      await expect(page).toHaveURL(/step=3$/)
      await expect(variables).toHaveText(contents, { useInnerText: true })
      await expect(page.getByRole('complementary', { name: '左侧辅助栏' })).toHaveAttribute('data-expanded', 'true')
    }
    await page.getByText('禅模式', { exact: true }).click()
    await expect(layout).toContainText('1:2:3')
    await layout.click()
    await page.getByRole('option', { name: '1:3:2', exact: true }).click()
    await page.getByText('禅模式', { exact: true }).click()
    await expect(layout).toContainText('1:3:2')
    await page.reload()
    await expect(layout).toContainText('1:3:2')
    await expect(page).toHaveURL(/step=3$/)
    await page.getByRole('link', { name: '返回结果查看器' }).click()
    await expect(layout).toHaveCount(0)
    await page.getByRole('link', { name: /开始逐步学习/ }).click()
    await expect(layout).toContainText('1:3:2')
    await page.goto('/bo/cases/multiway-endpoints/learn')
    await expect(layout).toContainText('1:3:2')
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}
