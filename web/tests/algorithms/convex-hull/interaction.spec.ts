import { expect, test } from '@playwright/test'
import { formatPoint, type Point } from '../../../src/geometry/geometry'

test.use({ locale: 'en-US' })

test('lists and canvas share hover, selection and duplicate positions', async ({ page }) => {
  await page.goto('/convex-hull/cases/duplicate-coordinates')
  const inputs = page.getByRole('region', { name: 'Input points', exact: true }).getByRole('listitem')
  const vertices = page.getByRole('region', { name: 'Hull vertices', exact: true }).getByRole('listitem')
  const origin = page.getByRole('button', { name: 'Point (0, 0)', exact: true })
  const interior = page.getByRole('button', { name: 'Point (2, 2)', exact: true })
  await expect(vertices).toHaveCount(4)
  await inputs.nth(4).hover()
  await expect(origin).toHaveAttribute('data-highlighted', 'true')
  await inputs.nth(4).getByRole('button').click()
  await page.getByRole('heading', { level: 1 }).hover()
  await expect(origin).toHaveAttribute('aria-pressed', 'true')
  await expect(inputs.nth(0)).toHaveAttribute('data-selected', 'true')
  await expect(inputs.nth(4)).toHaveAttribute('data-selected', 'true')
  await expect(vertices.nth(0)).toHaveAttribute('data-selected', 'true')

  await interior.hover()
  await expect(inputs.nth(5)).toHaveAttribute('data-highlighted', 'true')
  await expect(vertices.nth(0)).toHaveAttribute('data-highlighted', 'false')
  await interior.click()
  await expect(interior).toHaveAttribute('aria-pressed', 'true')
  await expect(origin).toHaveAttribute('aria-pressed', 'false')
  await expect(inputs.nth(5)).toHaveAttribute('data-selected', 'true')
  await expect(vertices.nth(0)).toHaveAttribute('data-selected', 'false')

  await vertices.nth(2).hover()
  const upperRight = page.getByRole('button', { name: 'Point (4, 4)', exact: true })
  await expect(upperRight).toHaveAttribute('data-highlighted', 'true')
  await vertices.nth(2).getByRole('button').click()
  await expect(upperRight).toHaveAttribute('aria-pressed', 'true')
  await origin.hover()
  await expect(inputs.nth(0)).toHaveAttribute('data-highlighted', 'true')
  await expect(inputs.nth(4)).toHaveAttribute('data-highlighted', 'true')
  await expect(vertices.nth(0)).toHaveAttribute('data-highlighted', 'true')
  await origin.focus()
  await page.keyboard.press('Enter')
  await expect(origin).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('status')).toHaveText('Input points: 6; hull vertices: 4')
  await expect(inputs).toHaveCount(6)

  await page.getByRole('link', { name: 'Back to cases', exact: true }).click()
  await page.getByRole('article', { name: 'Triangle and interior point', exact: true }).getByRole('button', { name: 'View details', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Input points: 4; hull vertices: 3')
  await expect(page.getByRole('button', { name: 'Point (0, 0)', exact: true })).toHaveAttribute('aria-pressed', 'false')
})

test('fractional vertices locate exact coordinates in both directions', async ({ page }) => {
  await page.goto('/convex-hull/cases/exact-fractions')
  const vertices = page.getByRole('region', { name: 'Hull vertices', exact: true }).getByRole('listitem')
  const inputs = page.getByRole('region', { name: 'Input points', exact: true }).getByRole('listitem')
  const fraction = page.getByRole('button', { name: 'Point (3/2, 0)', exact: true })
  await vertices.nth(1).getByRole('button').click()
  await expect(fraction).toHaveAttribute('aria-pressed', 'true')
  await fraction.focus()
  await page.keyboard.press('Space')
  await expect(fraction).toHaveAttribute('aria-pressed', 'false')
  await fraction.click()
  await expect(inputs.nth(1)).toHaveAttribute('data-selected', 'true')
  await expect(vertices.nth(1)).toHaveText('V1 (3/2, 0)')
  await page.keyboard.press('Escape')
  await expect(fraction).toHaveAttribute('aria-pressed', 'false')
})

test('canvas locates a point inside the long input list without scrolling the page', async ({ page }) => {
  await page.setViewportSize({ width: 1360, height: 900 })
  const pending = page.waitForResponse(response => response.url().endsWith('/api/convex-hull') && response.ok())
  await page.goto('/convex-hull/cases/hexagonal-snowflake')
  const response = await pending
  const points = response.request().postDataJSON().points as Point[]
  const inputs = page.getByRole('region', { name: 'Input points', exact: true })
  const row = inputs.getByRole('listitem').last()
  await expect(row).not.toBeInViewport()
  const before = await page.evaluate(() => window.scrollY)
  await page.getByRole('button', { name: `Point ${formatPoint(points.at(-1)!)}`, exact: true }).hover()
  await expect(row).toHaveAttribute('data-highlighted', 'true')
  await expect(row).toBeInViewport()
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
})
