import { expect, test } from '@playwright/test'

for (const browserName of ['chromium', 'webkit'] as const) {
  const browserTest = test.extend({ browserName, locale: 'en-US', viewport: { width: 1440, height: 900 } })
  browserTest(`zen mode preserves replay and guards shortcuts: ${browserName}`, async ({ page }) => {
    await page.goto('/convex-polygon-intersection/cases/irregular-overlap/learn?step=3')
    const zen = page.getByRole('switch', { name: 'Zen mode', exact: true })
    const controls = page.locator('.polygon-replay-controls')
    const action = page.getByRole('region', { name: 'Current action', exact: true })
    await expect(action).toBeVisible()
    await expect(zen).toHaveAttribute('aria-keyshortcuts', 'z')
    await page.getByText('Zen mode', { exact: true }).click()
    await expect(zen).toBeChecked()
    await expect(page.locator('.app-header')).toBeHidden()
    await expect(controls).toBeHidden()
    await expect(action).toBeVisible()
    await expect(page.getByRole('region', { name: 'Polygon A vertices', exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Collected candidates', exact: true })).toBeVisible()
    await expect(page).toHaveURL(/step=3$/)
    await page.getByRole('link', { name: 'Back to cases', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page).toHaveURL(/step=4$/)
    await page.reload()
    await expect(action).toBeVisible()
    await expect(zen).toBeChecked()
    await expect(controls).toBeHidden()
    await expect(page).toHaveURL(/step=4$/)
    await page.getByRole('button', { name: 'About this case', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('z')
    await expect(zen).toBeChecked()
    await page.keyboard.press('Escape')
    await page.getByRole('link', { name: 'Back to cases', exact: true }).focus()
    await page.keyboard.press('Control+z')
    await expect(zen).toBeChecked()
    await page.keyboard.down('z')
    await expect(zen).not.toBeChecked()
    await page.keyboard.down('z')
    await page.keyboard.up('z')
    await expect(zen).not.toBeChecked()
    await expect(page.locator('.app-header')).toBeVisible()
    await expect(controls).toBeVisible()
    await expect(page.getByRole('slider', { name: 'Teaching step' })).toHaveValue('4')
    await page.keyboard.press('z')
    for (const path of ['/convex-hull/cases/triangle-interior/learn', '/bo/cases/crossing/learn']) {
      await page.goto(path)
      await expect(zen).not.toBeChecked()
      await page.getByRole('link', { name: 'Back to cases', exact: true }).focus()
      await page.keyboard.press('z')
      await expect(zen).toBeChecked()
      await expect(page.locator('.app-header')).toBeHidden()
      await page.keyboard.press('z')
      await expect(zen).not.toBeChecked()
      await expect(page.locator('.app-header')).toBeVisible()
    }
  })
}
