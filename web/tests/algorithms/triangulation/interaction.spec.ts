import { expect, test, type Locator } from '@playwright/test'

test.use({ locale: 'en-US', viewport: { width: 1360, height: 900 } })

async function center(shape: Locator) {
  return shape.evaluate(node => {
    const polygon = node as SVGPolygonElement
    const matrix = polygon.getScreenCTM()!
    const points = Array.from(polygon.points)
    return new DOMPoint(points.reduce((sum, p) => sum + p.x, 0) / 3, points.reduce((sum, p) => sum + p.y, 0) / 3).matrixTransform(matrix).toJSON() as { x: number; y: number }
  })
}

test('triangles link hover, persistent selection and keyboard in both directions', async ({ page }) => {
  await page.goto('/triangulation/cases/concave')
  const rows = page.getByRole('region', { name: 'Triangles', exact: true }).getByRole('listitem')
  await expect(rows).toHaveCount(4)
  const shapes = page.locator('[data-triangle]')
  await rows.first().getByRole('button').hover()
  await expect(shapes.first()).toHaveAttribute('data-highlighted', 'true')
  await rows.first().getByRole('button').click()
  await page.getByRole('heading', { level: 1 }).hover()
  await expect(shapes.first()).toHaveAttribute('aria-pressed', 'true')
  const position = await center(shapes.last())
  await page.mouse.move(position.x, position.y)
  await expect(rows.last()).toHaveAttribute('data-highlighted', 'true')
  await page.mouse.click(position.x, position.y)
  await expect(rows.last()).toHaveAttribute('data-selected', 'true')
  await expect(rows.first()).toHaveAttribute('data-selected', 'false')
  await shapes.last().focus()
  await page.keyboard.press('Space')
  await expect(rows.last()).toHaveAttribute('data-selected', 'false')
  await page.keyboard.press('Enter')
  await expect(rows.last()).toHaveAttribute('data-selected', 'true')
  await page.keyboard.press('Escape')
  await expect(rows.last()).toHaveAttribute('data-selected', 'false')
  await rows.first().getByRole('button').focus()
  await page.keyboard.press('Space')
  await expect(shapes.first()).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Space')
  await expect(shapes.first()).toHaveAttribute('aria-pressed', 'false')
})

test('canvas locates a long real triangle list without scrolling the document', async ({ page }) => {
  await page.goto('/triangulation/cases/multiple-notches')
  const rows = page.getByRole('region', { name: 'Triangles', exact: true }).getByRole('listitem')
  await expect(rows).toHaveCount(50)
  await expect(rows.last()).not.toBeInViewport()
  const before = await page.evaluate(() => window.scrollY)
  const last = page.locator('[data-triangle]').last()
  const position = await center(last)
  await page.mouse.move(position.x, position.y)
  await expect(rows.last()).toHaveAttribute('data-highlighted', 'true')
  await expect(rows.last()).toBeInViewport()
  await page.mouse.click(position.x, position.y)
  await expect(rows.last()).toHaveAttribute('data-selected', 'true')
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
  await expect(page.getByRole('button', { name: 'Reset view', exact: true })).toBeInViewport()
})

test('triangle selection coexists with vertices and survives viewport changes without selecting on drag', async ({ page }) => {
  await page.goto('/triangulation/cases/convex')
  const rows = page.getByRole('region', { name: 'Triangles', exact: true }).getByRole('listitem')
  await expect(rows).toHaveCount(4)
  const shapes = page.locator('[data-triangle]')
  await rows.first().getByRole('button').click()
  const vertex = page.getByRole('button', { name: 'Point (0, 0)', exact: true })
  await vertex.click()
  await expect(vertex).toHaveAttribute('aria-pressed', 'true')
  await expect(shapes.first()).toHaveAttribute('aria-pressed', 'true')
  const text = await rows.allTextContents()
  const layer = page.locator('[data-layer="geometry"]')
  const initial = (await layer.getAttribute('transform'))!
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(layer).not.toHaveAttribute('transform', initial)
  const zoomed = (await layer.getAttribute('transform'))!
  const position = await center(shapes.last())
  await page.mouse.move(position.x, position.y)
  await page.mouse.down()
  await page.mouse.move(position.x + 25, position.y + 20, { steps: 5 })
  await page.mouse.up()
  await expect(layer).not.toHaveAttribute('transform', zoomed)
  await expect(shapes.first()).toHaveAttribute('aria-pressed', 'true')
  await expect(shapes.last()).toHaveAttribute('aria-pressed', 'false')
  await expect(vertex).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Zoom out', exact: true }).click()
  await page.getByRole('button', { name: 'Reset view', exact: true }).click()
  await expect(layer).toHaveAttribute('transform', initial)
  await expect(rows).toHaveText(text)
  await shapes.last().focus()
  await page.keyboard.press('Enter')
  await expect(rows.last()).toHaveAttribute('data-selected', 'true')
  await page.keyboard.press('Escape')
  await expect(vertex).toHaveAttribute('aria-pressed', 'false')
  await expect(rows.last()).toHaveAttribute('data-selected', 'false')
})

test('navigation, refresh and late failures cannot retain an old triangle selection', async ({ page }) => {
  await page.goto('/triangulation/cases/convex')
  const rows = page.getByRole('region', { name: 'Triangles', exact: true }).getByRole('listitem')
  await expect(rows).toHaveCount(4)
  await rows.first().getByRole('button').click()
  await page.reload()
  await expect(rows).toHaveCount(4)
  await expect(rows.first()).toHaveAttribute('data-selected', 'false')
  let release = () => {}
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/triangulation', async route => {
    if (route.request().postDataJSON().vertices.length !== 3) return route.continue()
    await pending
    await route.fulfill({ status: 500, body: 'late failure' })
  })
  await page.getByRole('link', { name: 'Back to cases', exact: true }).click()
  await page.getByRole('article', { name: 'Triangle', exact: true }).getByRole('button').click()
  await expect(page.getByRole('status')).toContainText('Computing')
  await expect(page.locator('[data-triangle]')).toHaveCount(0)
  await page.getByRole('link', { name: 'Back to cases', exact: true }).click()
  await page.getByRole('article', { name: 'Concave polygon', exact: true }).getByRole('button').click()
  await expect(rows).toHaveCount(4)
  const text = await rows.allTextContents()
  release()
  await expect(rows).toHaveText(text)
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('[data-triangle][aria-pressed="true"]')).toHaveCount(0)
})
