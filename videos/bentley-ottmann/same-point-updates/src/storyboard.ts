import { left } from "../../../shared/math/math-lines.ts";

export type Cue = { caption: string; target?: string; focus?: string };
export type Step = {
  id: string;
  text: string;
  first: string;
  action: string;
  cues: Cue[];
  thinkAfter?: number;
};
export type DiagramKind =
  | "members"
  | "order"
  | "equal"
  | "gap"
  | "neighbors"
  | "empty"
  | "discovery"
  | "queue"
  | "flow"
  | "cases";
type Page = {
  id: string;
  section: number;
  title: string;
  source: string;
  diagram?: DiagramKind;
  steps: Step[];
};
const cue = (caption: string, target?: string, focus?: string): Cue => ({
  caption,
  target,
  focus,
});
const step = (
  id: string,
  text: string,
  first: string,
  action: string,
  cues: Cue[],
  thinkAfter?: number,
): Step => ({ id, text, first, action, cues, thinkAfter });
const page = (p: Page) => ({
  ...p,
  lines: p.steps,
  groups: [left(p.steps.length)],
  holdAfterSeconds: 3,
});

